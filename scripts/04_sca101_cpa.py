HW = np.array([bin(x).count("1") for x in range(256)], dtype=np.float64)

d = np.load(DATA)
traces = d["traces"].astype(np.float64)   # (N, T)
pt = d["textins"]                          # (N, 16)
real_key = d["key"]
N, T = traces.shape
print(f">>> 載入 {N} 條波形,每條 {T} 點")

# 事先中心化 traces(所有位元組共用)
Tc = traces - traces.mean(axis=0, keepdims=True)
Tnorm = np.sqrt((Tc ** 2).sum(axis=0))     # (T,)

recovered = np.zeros(16, dtype=np.uint8)
best_corr = np.zeros(16)
byte0_scores = None

for b in range(16):
    # 假設矩陣 H: (N, 256) = HW(Sbox[pt_b ^ guess])
    H = HW[SBOX[pt[:, b][:, None] ^ np.arange(256)[None, :]]]  # (N,256)
    Hc = H - H.mean(axis=0, keepdims=True)
    Hnorm = np.sqrt((Hc ** 2).sum(axis=0))                     # (256,)
    # 相關矩陣 (256, T)
    corr = (Hc.T @ Tc) / (Hnorm[:, None] * Tnorm[None, :] + 1e-12)
    score = np.abs(corr).max(axis=1)                           # 每個 guess 的最大相關
    guess = int(score.argmax())
    recovered[b] = guess
    best_corr[b] = score[guess]
    if b == 0:
        byte0_scores = score.copy()

print("真實金鑰 :", bytes(real_key).hex())
print("還原金鑰 :", bytes(recovered).hex())
ok = np.array_equal(recovered, real_key)
print("完全相符 :", ok, f"({int((recovered==real_key).sum())}/16 位元組正確)")
print("各位元組最佳相關係數: min=%.3f  mean=%.3f" % (best_corr.min(), best_corr.mean()))

