def cpa(tr, pt):
    Tc = tr - tr.mean(0, keepdims=True); Tn = np.sqrt((Tc**2).sum(0))
    out = np.zeros(16, np.uint8)
    for b in range(16):
        H = HW[SBOX[pt[:,b][:,None] ^ np.arange(256)[None,:]]]
        Hc = H - H.mean(0, keepdims=True); Hn = np.sqrt((Hc**2).sum(0))
        corr = np.abs((Hc.T @ Tc)/(Hn[:,None]*Tn[None,:]+1e-12)).max(1)
        out[b] = corr.argmax()
    return out

def dpa(tr, pt):
    out = np.zeros(16, np.uint8)
    for b in range(16):
        best, bg = -1, 0
        for g in range(256):
            bit = (SBOX[pt[:,b]^g] >> 0) & 1
            o, z = tr[bit==1], tr[bit==0]
            if len(o)==0 or len(z)==0: continue
            dom = np.abs(o.mean(0)-z.mean(0)).max()
            if dom > best: best, bg = dom, g
        out[b] = bg
    return out

